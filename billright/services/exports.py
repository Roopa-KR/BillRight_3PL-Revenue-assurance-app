XLSX = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"


def _meta(s, cur, site_id, period_id):
    h = ms.header(s, cur.scope, site_id, period_id)
    return [("Site", h["site"].name), ("Period", h["period"].label if h["period"] else "—"), ("Run ID", h["run"].id if h["run"] else "No run"),
            ("Data as of", h["data_as_of"].isoformat() if h["data_as_of"] else "—"),
            ("Data label", ", ".join(h["data_labels"]) if h["data_labels"] else "Real data"), ("Generated", dt.datetime.now(dt.timezone.utc).isoformat()),
            ("Generated by", cur.user.email)], h


def _num(v):
    return float(v) if isinstance(v, Decimal) else v  # Excel cells; values already rounded by the engine


def _sheet(wb, title, meta, columns, rows, money_cols=()):
    ws = wb.create_sheet(title[:31])
    for k, v in meta:
        ws.append([k, v])
    if any(k == "Data label" and v != "Real data" for k, v in meta):
        ws.cell(row=5, column=2).fill = PatternFill("solid", fgColor="FFF4D6")
    ws.append([])
    ws.append(columns)
    for c in ws[ws.max_row]:
        c.font = Font(bold=True)
    for r in rows:
        ws.append([_num(x) for x in r])
    for idx in money_cols:
        for row in ws.iter_rows(min_row=len(meta) + 3, min_col=idx + 1, max_col=idx + 1):
            for cell in row:
                cell.number_format = '#,##0.00;-#,##0.00'
    for i, col in enumerate(columns, start=1):
        ws.column_dimensions[ws.cell(row=len(meta) + 2, column=i).column_letter].width = max(12, min(48, len(str(col)) + 4))
    return ws


def _wb():
    wb = Workbook()
    wb.remove(wb.active)
    return wb


def _save(wb):
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def build(s, cur, name, site_id, period_id, fmt="xlsx"):
    perm = PERMS.get(name)
    if perm is None:
        abort(404)
    if not any(cur.can(p) for p in perm.split("|")):
        abort(403)
    meta, h = _meta(s, cur, site_id, period_id)
    label = h["period"].label if h["period"] else "none"
    fn = globals()["_" + name]
    return fn(s, cur, site_id, period_id, meta, h, fmt, label)


# 1 ----------------------------------------------------------------- invoice adjustment file
def adjustment_rows(s, cur, site_id, period_id):
    rows = ms.leakage_rows(s, cur.scope, site_id, period_id, include_carried=False)
    users = ms.user_names(s)
    out = []
    for r in rows:
        it = r["item"]
        if it.decision not in ("bill_now", "issue_credit") or not leak_svc.is_final(s, cur.actor, it):
            continue
        inv = s.execute(select(m.InvoiceHeader.invoice_number).join(m.InvoiceLine, m.InvoiceLine.invoice_header_id == m.InvoiceHeader.id)
                        .join(m.LeakageEvidence, m.LeakageEvidence.invoice_line_id == m.InvoiceLine.id)
                        .where(m.LeakageEvidence.leakage_item_id == it.id)).scalars().first()
        qty = Decimal(it.billable_quantity) - Decimal(it.billed_quantity)
        approver = users.get(it.approved_by) if it.approved_by else f"Below threshold; decided by {users.get(it.decided_by)}"
        out.append([r["customer_code"], inv or "New invoice line", r["charge"], qty, it.contract_unit_price, Decimal(it.gap_amount),
                    f"{RULE_NAMES[it.rule_code]}: {r['what']}" + (f" Reason: {it.decision_reason}" if it.decision_reason else ""), f"LKG-{it.id}", approver])
    return out


ADJ_COLS = ["Customer", "Invoice reference", "Charge code", "Quantity", "Unit price", "Amount", "Reason", "Leakage item ID", "Approver"]


def _adjustments(s, cur, site_id, period_id, meta, h, fmt, label):
    rows = adjustment_rows(s, cur, site_id, period_id)
    if fmt == "csv":
        buf = io.StringIO()
        w = csv.writer(buf)
        for k, v in meta:
            w.writerow([f"# {k}", v])
        w.writerow(ADJ_COLS)
        for r in rows:
            w.writerow(["" if x is None else x for x in r])
        return buf.getvalue().encode(), "text/csv", f"invoice_adjustments_{label}.csv"
    wb = _wb()
    _sheet(wb, "Invoice adjustments", meta, ADJ_COLS, rows, money_cols=(5,))
    return _save(wb), XLSX, f"invoice_adjustments_{label}.xlsx"


# 2 ----------------------------------------------------------------- leakage register
def _leakage_register(s, cur, site_id, period_id, meta, h, fmt, label):
    rows = ms.leakage_rows(s, cur.scope, site_id, period_id)
    users = ms.user_names(s)
    data = []
    hist = []
    for r in rows:
        it = r["item"]
        data.append([f"LKG-{it.id}", r["customer_code"], r["charge"], r["period"], it.rule_code, RULE_NAMES[it.rule_code], ", ".join(r["also"]), r["what"],
                     r["direction"], Decimal(it.billable_quantity), Decimal(it.billed_quantity), r["billable"], r["billed"], r["gap"], r["status_label"],
                     r["decision_label"], it.decision_reason, users.get(it.decided_by), it.decided_at.isoformat() if it.decided_at else None,
                     users.get(it.approved_by), it.invoiced_amount, "carried" if r["carried"] else ""])
        for a in s.execute(select(m.AuditLog).where(m.AuditLog.entity == "leakage_item", m.AuditLog.entity_id == str(it.id)).order_by(m.AuditLog.id)).scalars():
            hist.append([f"LKG-{it.id}", a.at.isoformat(), users.get(a.user_id, "system"), a.action, a.reason])
    wb = _wb()
    _sheet(wb, "Leakage register", meta, ["Item", "Customer", "Charge", "Period", "Rule", "Rule name", "Also matches", "What happened", "Direction",
                                          "Billable qty", "Billed qty", "Billable", "Billed", "Gap", "Status", "Decision", "Reason", "Decided by",
                                          "Decided at", "Approved by", "Invoiced", "Note"], data, money_cols=(11, 12, 13, 20))
    _sheet(wb, "History", meta, ["Item", "When", "Who", "Action", "Reason"], hist)
    return _save(wb), XLSX, f"leakage_register_{label}.xlsx"


# 3 ----------------------------------------------------------------- reconciliation
def _reconciliation(s, cur, site_id, period_id, meta, h, fmt, label):
    d = ms.reconciliation(s, cur.scope, site_id, period_id)
    rows = [[r["customer"], r["charge"], r["billable_qty"], r["billed_qty"], r["billable"], r["billed"], r["gap"], r["status"], ", ".join(r["rules"]), r["note"]]
            for r in d["rows"]]
    if d["totals"]:
        rows.append(["Site total", "", None, None, d["totals"]["billable"], d["totals"]["billed"], d["totals"]["gap"], "", "", ""])
    wb = _wb()
    _sheet(wb, "Reconciliation", meta, ["Customer", "Charge", "Billable qty", "Billed qty", "Billable", "Billed", "Gap", "Status", "Rules", "Note"], rows,
           money_cols=(4, 5, 6))
    # matrix view: customers x charges (gap)
    if d["rows"]:
        charges = d["charges"]
        mat = []
        for cu in d["customers"]:
            cells = {r["charge"]: r["gap"] for r in d["rows"] if r["customer"] == cu}
            mat.append([cu] + [cells.get(ch, Decimal(0)) for ch in charges] + [d["by_customer"][cu]["gap"]])
        mat.append(["Total"] + [d["by_charge"][ch]["gap"] for ch in charges] + [d["totals"]["gap"]])
        _sheet(wb, "Gap matrix", meta, ["Customer"] + charges + ["Total"], mat, money_cols=tuple(range(1, len(charges) + 2)))
    return _save(wb), XLSX, f"billing_reconciliation_{label}.xlsx"


# 4 ----------------------------------------------------------------- customer P&L
PNL_COLS = ["Customer", "Name", "Revenue", "Direct cost", "Allocated shared cost", "Total cost", "Site profit", "Margin %", "Orders", "Cost per order",
            "Confirmed, not yet invoiced"]


def _pnl_rows(p):
    na = lambda v: "Not available" if v is None else v
    rows = [[r["customer"], r["customer_name"], r["revenue"], na(r["direct_cost"]), na(r["shared_cost"]), na(r["total_cost"]), na(r["site_profit"]),
             r["margin_display"] if r["margin_display"] is not None else "Not available", r["orders"],
             r["cost_per_order"] if r["cost_per_order"] is not None else "Not available", r["confirmed_not_invoiced"]] for r in p["rows"]]
    st = p["site"]
    if st and not st["scoped"] and st["unassigned_cost"] is not None:
        rows.append(["Unassigned cost", "", None, None, None, st["unassigned_cost"], -st["unassigned_cost"], None, None, None, None])
    if st:
        rows.append(["Site total" if not st["scoped"] else "Total (your customers)", "", st["revenue"], None, None, na(st["total_cost"]), na(st["site_profit"]),
                     na(st["margin_display"]), None, None, None])
        if st.get("profit_before_financing_tax") is not None:
            rows.append(["Unallocated central overhead", "", None, None, None, None, -st["central_overhead"], None, None, None, None])
            rows.append(["Profit before financing and tax", "", None, None, None, None, st["profit_before_financing_tax"], None, None, None, None])
    return rows


def _customer_pnl(s, cur, site_id, period_id, meta, h, fmt, label):
    p = ms.customers_pnl(s, cur.scope, site_id, period_id)
    if fmt == "pdf":
        return _pnl_pdf(s, cur, site_id, period_id, meta, p), "application/pdf", f"customer_pnl_{label}.pdf"
    wb = _wb()
    _sheet(wb, "Site summary", meta, PNL_COLS, _pnl_rows(p), money_cols=(2, 3, 4, 5, 6, 9, 10))
    for r in p["rows"]:
        d = ms.customer_detail(s, cur.scope, site_id, period_id, r["customer_id"])
        rows = [["Revenue", "", r["revenue"]]] + [[c["label"], c["method"], -c["amount"]] for c in d["categories"]] + [["Site profit", "", r["site_profit"]],
                                                                                                                    ["Margin %", "", r["margin_display"]]]
        _sheet(wb, r["customer"], meta, ["Line", "Method", "Amount"], rows, money_cols=(2,))
    return _save(wb), XLSX, f"customer_pnl_{label}.xlsx"


def _pdf_doc():
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import SimpleDocTemplate
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=28, rightMargin=28, topMargin=28, bottomMargin=28)
    return buf, doc, getSampleStyleSheet()


def _table(data):
    from reportlab.lib import colors
    from reportlab.platypus import Table, TableStyle
    t = Table(data, repeatRows=1)
    t.setStyle(TableStyle([("FONT", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                           ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF0F3")), ("ALIGN", (2, 1), (-1, -1), "RIGHT")]))
    return t


def _fmt(v):
    from ..web import fmt_money
    if isinstance(v, Decimal):
        return fmt_money(v)
    return "" if v is None else str(v)


def _meta_flow(meta, styles):
    from reportlab.platypus import Paragraph
    return [Paragraph(" · ".join(f"<b>{k}</b>: {v}" for k, v in meta), styles["Normal"])]


def _pnl_pdf(s, cur, site_id, period_id, meta, p):
    from reportlab.platypus import PageBreak, Paragraph, Spacer
    buf, doc, st = _pdf_doc()
    story = [Paragraph("Customer P&amp;L — site summary", st["Title"])] + _meta_flow(meta, st) + [Spacer(1, 8)]
    story.append(_table([PNL_COLS] + [[_fmt(x) for x in r] for r in _pnl_rows(p)]))
    for r in p["rows"]:
        d = ms.customer_detail(s, cur.scope, site_id, period_id, r["customer_id"])
        story += [PageBreak(), Paragraph(f"{r['customer']} · {r['customer_name']}", st["Title"])] + _meta_flow(meta, st) + [Spacer(1, 8)]
        rows = [["Line", "Method", "Amount"], ["Revenue", "", _fmt(r["revenue"])]] + [[c["label"], c["method"], _fmt(-c["amount"])] for c in d["categories"]]
        rows += [["Site profit", "", _fmt(r["site_profit"])], ["Margin", "", f"{r['margin_display']}%" if r["margin_display"] is not None else "Not available"]]
        story.append(_table(rows))
        if d["insight"] and d["insight"].get("applies"):
            story += [Spacer(1, 8), Paragraph("<b>What is happening:</b> " + d["insight"]["what"], st["Normal"]),
                      Paragraph("<b>Why:</b> " + " ".join(d["insight"]["why"]), st["Normal"]), Paragraph("<b>What to check:</b> " + d["insight"]["check"], st["Normal"])]
    doc.build(story)
    return buf.getvalue()


# 5 ----------------------------------------------------------------- expense and allocation statement
def _expense_allocation(s, cur, site_id, period_id, meta, h, fmt, label):
    d = ms.costs(s, cur.scope, site_id, period_id)
    wb = _wb()
    _sheet(wb, "Expense ledger", meta, ["Category", "Description", "Source", "Reference", "Payment recipient", "Direct customer", "Amount"],
           [[ms.CATEGORY_LABELS[x.expense_category], x.description, x.source_type, x.source_ref, ms.RECIPIENT_LABELS.get(x.payment_recipient_type),
             (s.get(m.Customer, x.customer_id).code if x.customer_id else None), x.amount] for x in d["lines"]]
           + [["Total", "", "", "", "", "", d["total"]]], money_cols=(6,))
    _sheet(wb, "Payment recipients", meta, ["Recipient", "Amount", "Treatment"],
           [[w["label"], w["amount"], w["treatment"]] for w in d["who"]] + [["Total", d["recipients_total"], "Matches the expense ledger" if d["ledger_reconciles"] else f"Difference {d['difference']}"]],
           money_cols=(1,))
    custs = d["customers"]
    _sheet(wb, "Allocation matrix", meta, ["Category", "Method", "Driver"] + [c["code"] for c in custs] + ["Unassigned", "Pool total", "Reconciles"],
           [[r["label"], r["method"], r["driver"].description if r["driver"] else "", *[r["cells"][c["id"]] for c in custs], r["unassigned"], r["pool"], "Yes" if r["check"] else "No"]
            for r in d["matrix"]], money_cols=tuple(range(3, len(custs) + 5)))
    drv_rows = []
    for dr in s.execute(select(m.AllocationDriver).where(m.AllocationDriver.site_id == site_id)).scalars():
        for q in s.execute(select(m.AllocationDriverQuantity).where(m.AllocationDriverQuantity.driver_id == dr.id, m.AllocationDriverQuantity.period_id == period_id)).scalars():
            drv_rows.append([ms.CATEGORY_LABELS[dr.expense_category], ms.DRIVER_LABELS[dr.driver_type], dr.status, dr.data_label or "",
                             s.get(m.Customer, q.customer_id).code if q.customer_id else "Unassigned", q.quantity, q.source_ref])
    _sheet(wb, "Drivers", meta, ["Category", "Driver", "Status", "Label", "Customer", "Quantity", "Source"], drv_rows)
    return _save(wb), XLSX, f"expense_allocation_{label}.xlsx"


# 6 ----------------------------------------------------------------- close report + receivables / payables
def _close_report(s, cur, site_id, period_id, meta, h, fmt, label):
    from reportlab.platypus import Paragraph, Spacer
    from .close import run_checks
    checks = run_checks(s, cur.actor, cur.scope, period_id)
    p = ms.customers_pnl(s, cur.scope, site_id, period_id)
    users = ms.user_names(s)
    buf, doc, st = _pdf_doc()
    period = h["period"]
    story = [Paragraph(f"Period close report — {label}", st["Title"])] + _meta_flow(meta, st)
    story.append(Paragraph(f"Status: {period.status}" + (f", closed {period.closed_at:%d %b %Y} by {users.get(period.closed_by)}, close run #{period.close_run_id}" if period.closed_at else ""), st["Normal"]))
    story += [Spacer(1, 8), _table([["#", "Check", "Result", "Detail"]] + [[str(c.no), Paragraph(c.title, st["BodyText"]),
                                                                           "Passed" if c.passed else ("Acknowledged" if c.acknowledged else "Failed"),
                                                                           Paragraph(c.detail + (" Acknowledged: " + c.acknowledged["reason"] if c.acknowledged else "") + "".join("<br/>• " + i for i in c.items), st["BodyText"])]
                                                                          for c in checks])]
    if p["available"]:
        story += [Spacer(1, 10), Paragraph("Totals", st["Heading2"]), _table([PNL_COLS] + [[_fmt(x) for x in r] for r in _pnl_rows(p)])]
    pm = ms.period_leakage_metrics(s, cur.scope, site_id, period_id)
    story += [Spacer(1, 10), Paragraph("Leakage", st["Heading2"]),
              _table([["Flagged", "Confirmed", "Invoiced", "Over-billing found"], [_fmt(pm["flagged"]), _fmt(pm["confirmed"]), _fmt(pm["invoiced"]), _fmt(pm["over_billing"])]])]
    acks = [c for c in checks if c.acknowledged]
    story += [Spacer(1, 10), Paragraph("Exceptions acknowledged", st["Heading2"])]
    story += [Paragraph(f"Check {c.no}: {c.acknowledged['reason']} ({users.get(c.acknowledged['by'])})", st["Normal"]) for c in acks] or [Paragraph("None.", st["Normal"])]
    doc.build(story)
    return buf.getvalue(), "application/pdf", f"period_close_report_{label}.pdf"


def _receivables_payables(s, cur, site_id, period_id, meta, h, fmt, label):
    run = h["run"]
    batches = run.input_batch_ids if run else []
    wb = _wb()
    rec = [[hd.invoice_number, s.get(m.Customer, hd.customer_id).code, hd.invoice_date, l.raw_charge_code, l.amount, l.adjustment_ref]
           for l, hd in s.execute(select(m.InvoiceLine, m.InvoiceHeader).join(m.InvoiceHeader, m.InvoiceHeader.id == m.InvoiceLine.invoice_header_id)
                                  .where(m.InvoiceHeader.site_id == site_id, m.InvoiceHeader.period_id == period_id, m.InvoiceHeader.import_batch_id.in_(batches or [-1]))
                                  .order_by(m.InvoiceHeader.invoice_number, m.InvoiceLine.line_number)).all()]
    _sheet(wb, "Receivables", meta, ["Invoice", "Customer", "Invoice date", "Charge", "Amount", "Adjustment ref"], rec, money_cols=(4,))
    pay = [[x.payment_recipient_type, x.description, x.source_type, x.source_ref, x.amount] for x in ms.costs(s, cur.scope, site_id, period_id)["lines"]]
    _sheet(wb, "Payables", meta, ["Recipient type", "Description", "Source", "Reference", "Amount"], pay, money_cols=(4,))
    return _save(wb), XLSX, f"receivables_payables_{label}.xlsx"


# 7 ----------------------------------------------------------------- pilot results
def _pilot_results(s, cur, site_id, period_id, meta, h, fmt, label):
    rows = ms.pilot_metrics(s, cur.scope, site_id)
    sub = get_setting(s, cur.tenant_id, "pilot.subscription_cost")
    wb = _wb()
    _sheet(wb, "Pilot results", meta, ["Period", "Leakage flagged", "Leakage confirmed", "Leakage invoiced", "Recovery rate", "Leakage prevented",
                                       "Precision", "Decisions", "Over-billing found", "Time to close (days)", "Labor attribution coverage",
                                       "Cannot-rate items", "Unresolved customer records"],
           [[r["period"], r["flagged"], r["confirmed"], r["invoiced"], r["recovery_rate"] if r["recovery_rate"] is not None else "Not available", r["prevented"],
             r["precision"] if r["precision"] is not None else "Not available", r["decided_count"], r["over_billing"],
             r["time_to_close"] if r["time_to_close"] is not None else "Not closed", r["labor_coverage"] if r["labor_coverage"] is not None else "Not available",
             r["cannot_rate_count"], r["unresolved_count"]] for r in rows], money_cols=(1, 2, 3, 5, 8))
    recovered = sum((r["invoiced"] for r in rows), Decimal(0))
    prevented = sum((r["prevented"] for r in rows), Decimal(0))
    _sheet(wb, "Return on subscription", meta, ["Recovered", "Prevented", "Subscription cost", "Return on subscription"],
           [[recovered, prevented, sub if sub is not None else "Not set (setting pilot.subscription_cost)",
             ((recovered + prevented) / sub) if sub else "Not available"]], money_cols=(0, 1, 2))
    return _save(wb), XLSX, f"pilot_results_{h['site'].code}.xlsx"
